/// One crop's computed match against the farmer's soil reading, shown on
/// the report screen's "Recommended Crop" card.
@immutable
final class CropSuitability {
  const CropSuitability({required this.name, required this.emoji, required this.percent});

  final String name;
  final String emoji;

  /// 0–100. Relative closeness of the soil reading to this crop's ideal
  /// N/P/K/pH band — a comparison tool, not a yield guarantee.
  final int percent;
}

/// A single row of the report screen's "What Should You Do?" action plan.
@immutable
final class ActionStep {
  const ActionStep({required this.title, required this.description});

  final String title;
  final String description;
}

/// A single row of the "Fertilizer Recommendation" table — what to do for
/// one input (Nitrogen / Phosphorus / Potassium / Organic manure), plus a
/// plain-language reason so the farmer understands *why*, not just *what*.
@immutable
final class FertilizerRecommendationRow {
  const FertilizerRecommendationRow({
    required this.input,
    required this.recommendation,
    required this.reason,
  });

  final String input;
  final String recommendation;
  final String reason;
}

/// "What Your Soil Needs" — the single most pressing issue found in the
/// reading (worst-scoring nutrient/pH/moisture, or null when everything is
/// in the optimal band), plus 2–3 plain-language impact bullets. Never a
/// medical-style diagnosis — just the same traffic-light logic already
/// used elsewhere, surfaced as a headline instead of buried in a grid.
@immutable
final class SoilIssue {
  const SoilIssue({required this.title, required this.emoji, required this.impacts});

  final String title;
  final String emoji;
  final List<String> impacts;
}

/// A single previously-used fertilizer the farmer optionally logs before
/// running a scan. Only the name is required — quantity and date are
/// free-text/optional, matching how a smallholder farmer actually
/// remembers past applications (rarely with lab precision).
@immutable
final class FertilizerHistoryEntry {
  const FertilizerHistoryEntry({required this.name, this.quantity, this.date});

  final String name;

  /// Free-text quantity as the farmer remembers it (e.g. "50 kg", "2 bags").
  /// Intentionally not a parsed numeric — never used for dosage math, only
  /// displayed back and passed along as context.
  final String? quantity;
  final DateTime? date;
}

/// One previously-used conventional fertilizer paired with a short list of
/// NCONF-referenced organic/natural alternatives for the nutrient it
/// supplies. Never a 1:1 replacement claim, never a dosage — see
/// `GeminiAgriService._buildFertilizerOrganicAlternatives`.
@immutable
final class FertilizerAlternativeGroup {
  const FertilizerAlternativeGroup({
    required this.previousFertilizer,
    required this.alternatives,
  });

  final String previousFertilizer;
  final List<String> alternatives;
}

@immutable
final class FertilizerDose {
  const FertilizerDose({
