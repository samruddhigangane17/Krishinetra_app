enum SoilHealthStatus { good, moderate, poor }

extension SoilHealthStatusX on SoilHealthStatus {
  Color get color {
    switch (this) {
      case SoilHealthStatus.good:
        return const Color(0xFF2E7D32);
      case SoilHealthStatus.moderate:
        return const Color(0xFFF08C1D);
      case SoilHealthStatus.poor:
        return const Color(0xFFD32F2F);
    }
  }

  String get label {
    switch (this) {
      case SoilHealthStatus.good:
        return 'Optimal';
      case SoilHealthStatus.moderate:
        return 'Moderate Deficit';
      case SoilHealthStatus.poor:
        return 'Critical Deficit';
    }
  }
}

/// Single source of truth for agronomic reference ranges, shared by the
/// offline rule-based engine (scoring, fertilizer math) and the report
/// screen's per-nutrient traffic-light badges — so the two never drift out
/// of sync with each other.
abstract final class SoilThresholds {
  static const double idealNitrogenLow = 50;
  static const double idealNitrogenHigh = 70;
  static const double idealPhosphorusLow = 25;
  static const double idealPhosphorusHigh = 35;
  static const double idealPotassiumLow = 25;
  static const double idealPotassiumHigh = 35;
  static const double idealPhLow = 6.2;
  static const double idealPhHigh = 7.2;

  /// Ideal volumetric soil-moisture band (%) for most field crops at the
  /// growth stage a farmer is likely testing at — wide enough to cover
  /// several crop types without a per-crop moisture model.
  static const double idealMoistureLow = 20;
  static const double idealMoistureHigh = 35;

  /// Buckets a raw reading into good/moderate/poor based on how far it
  /// sits from the [low, high] ideal band, using [moderateMargin] (as a
  /// fraction of the band width) as the "moderate" tolerance zone before a
  /// reading is considered critical.
  static SoilHealthStatus statusFor(
    double value,
    double low,
    double high, {
    double moderateMargin = 0.35,
  }) {
    if (value >= low && value <= high) return SoilHealthStatus.good;

    final double range = high - low;
    final double margin = range * moderateMargin;

    if (value >= low - margin && value <= high + margin) {
      return SoilHealthStatus.moderate;
    }
    return SoilHealthStatus.poor;
  }

  static SoilHealthStatus nitrogenStatus(double value) =>
      statusFor(value, idealNitrogenLow, idealNitrogenHigh);

  static SoilHealthStatus phosphorusStatus(double value) =>
      statusFor(value, idealPhosphorusLow, idealPhosphorusHigh);

  static SoilHealthStatus potassiumStatus(double value) =>
      statusFor(value, idealPotassiumLow, idealPotassiumHigh);

  static SoilHealthStatus phStatus(double value) =>
      statusFor(value, idealPhLow, idealPhHigh, moderateMargin: 0.2);

  static SoilHealthStatus moistureStatus(double value) =>
      statusFor(value, idealMoistureLow, idealMoistureHigh);

  /// Same 75/45 composite-score thresholds the assessment engine uses
  /// (kept here as the single reusable source so new call sites — like
  /// the history trend chart — don't duplicate the cutoffs).
  static SoilHealthStatus statusForScore(int score) {
    if (score >= 75) return SoilHealthStatus.good;
    if (score >= 45) return SoilHealthStatus.moderate;
    return SoilHealthStatus.poor;
  }
}

