  final String description;
}

@immutable
final class SoilInputs {
  const SoilInputs({
    this.nitrogen,
    this.phosphorus,
    this.potassium,
    this.ph,
    this.moisture,
    this.selectedCrop,
    this.cropStage,
    this.usesOrganicInputs,
    this.imagePath,
    this.imageBytes,
    this.imageMimeType,
    this.fertilizerHistory = const [],
  });

  /// Lab soil readings are now optional — a farmer with no soil-test kit
  /// can run a scan on a crop/soil photo alone. When a reading is null,
  /// [effectiveNitrogen] etc. fall back to the ideal-band midpoint so the
  /// deterministic scoring/dosing math downstream never has to null-check.
  final double? nitrogen;
  final double? phosphorus;
  final double? potassium;
  final double? ph;

  /// Optional soil-moisture reading (%), independent of the N/P/K/pH
  /// "complete set" required for the offline engine — a farmer can add
  /// it, skip it, or enter it alone alongside a photo.
  final double? moisture;
  final String? selectedCrop;

  /// Optional growth stage at the time of scanning (e.g. "Sowing",
  /// "Vegetative", "Flowering", "Maturity") — used only by the
  /// weather-advisory engine to sharpen a couple of its rules (e.g.
  /// flagging rain risk specifically during flowering). Never required.
  final String? cropStage;

  /// Whether the farmer reported using organic/bio-based inputs (compost,
  /// FYM, vermicompost, biofertilizers, etc.) alongside or instead of
  /// conventional chemical fertilizer. Null means the farmer wasn't asked
  /// or skipped the question — deliberately kept distinct from `false`
  /// (asked and said no), since scheme-matching logic treats "unknown"
  /// differently from a confirmed "no".
  final bool? usesOrganicInputs;

  /// Display-only filename/path for the attached crop photo, if any.
  final String? imagePath;

  /// Raw bytes of the attached crop photo, used for Base64 encoding when
  /// sending a multimodal request to Gemini. Using bytes (rather than a
  /// filesystem path) is what makes this work identically on web, where
  /// there is no real file path to read from.
  final Uint8List? imageBytes;

  /// MIME type of [imageBytes] (e.g. `image/jpeg`), captured at pick time
  /// so the Gemini request declares the correct `inline_data.mime_type`.
  final String? imageMimeType;

  /// Optional, farmer-logged fertilizers used before this scan. Purely
  /// contextual — never treated as proof of a deficiency/excess, and
  /// never used to alter [nitrogen]/[phosphorus]/[potassium]/[ph] above.
  final List<FertilizerHistoryEntry> fertilizerHistory;

  bool get hasImage => imageBytes != null && imageBytes!.isNotEmpty;

  /// True only when the farmer entered all four lab readings.
  bool get hasCompleteSoilData =>
      nitrogen != null && phosphorus != null && potassium != null && ph != null;

  /// True when at least one reading was entered (used to decide what to
  /// tell Gemini/the offline engine — a partial set is still worth sending).
  bool get hasAnySoilData =>
      nitrogen != null || phosphorus != null || potassium != null || ph != null;

  /// True for the "image-only" flow: a photo was given and no lab
  /// readings were entered at all.
  bool get isImageOnly => hasImage && !hasAnySoilData;

  double get effectiveNitrogen =>
      nitrogen ?? (SoilThresholds.idealNitrogenLow + SoilThresholds.idealNitrogenHigh) / 2;
  double get effectivePhosphorus =>
      phosphorus ?? (SoilThresholds.idealPhosphorusLow + SoilThresholds.idealPhosphorusHigh) / 2;
  double get effectivePotassium =>
      potassium ?? (SoilThresholds.idealPotassiumLow + SoilThresholds.idealPotassiumHigh) / 2;
  double get effectivePh =>
      ph ?? (SoilThresholds.idealPhLow + SoilThresholds.idealPhHigh) / 2;
  double get effectiveMoisture =>
      moisture ?? (SoilThresholds.idealMoistureLow + SoilThresholds.idealMoistureHigh) / 2;
}

/// The full result of a soil (and optionally crop-image) analysis —
/// whether produced by Gemini or by the offline rule-based agronomy
/// engine. The UI never needs to know which source produced it beyond
/// [poweredByGemini], which drives a small transparency badge on the
/// report screen.
@immutable
final class SoilHealthAssessment {
  const SoilHealthAssessment({
    required this.healthScore,
    required this.status,
    required this.agronomistSummary,
    required this.recommendedCrop,
    required this.yieldIncreasePercent,
    required this.fertilizerDoses,
    required this.scheduleSteps,
    required this.organicAlternatives,
    required this.dos,
    required this.donts,
    required this.poweredByGemini,
    required this.generatedAt,
    required this.inputs,
    this.diseaseName,
    this.diseaseTreatment,
    this.fertilizerContextNotes = const [],
    this.fertilizerOrganicAlternatives = const [],
    this.cropSuitabilities = const [],
    this.primaryIssue,
    this.actionPlan = const [],
    this.fertilizerRecommendationRows = const [],
  });

  final int healthScore;
  final SoilHealthStatus status;
  final String agronomistSummary;
  final String recommendedCrop;
  final int yieldIncreasePercent;
  final List<FertilizerDose> fertilizerDoses;
  final List<ScheduleStep> scheduleSteps;
  final List<String> organicAlternatives;
  final List<String> dos;
  final List<String> donts;
  final bool poweredByGemini;
  final DateTime generatedAt;
  final SoilInputs inputs;

  /// Name of a detected crop disease/pest issue from the uploaded photo,
  /// or null if no photo was analyzed or no issue was detected.
  final String? diseaseName;

  /// Recommended treatment for [diseaseName], or null when there's no
  /// detected disease to treat.
  final String? diseaseTreatment;

  bool get hasDiseaseFinding => diseaseName != null && diseaseName!.isNotEmpty;

  /// Short, non-diagnostic notes connecting the farmer's logged fertilizer
  /// history to this soil test's results (e.g. "Urea is a Nitrogen
  /// fertilizer; your soil shows Low Nitrogen"). Empty when no history was
  /// logged, or none of it maps to a recognized fertilizer.
  final List<String> fertilizerContextNotes;

  /// NCONF-referenced organic/natural alternatives grouped by the
  /// previously-used conventional fertilizer they relate to. Empty when no
  /// history was logged, or none of it maps to a recognized fertilizer.
  final List<FertilizerAlternativeGroup> fertilizerOrganicAlternatives;

  /// Best-fit crop plus 2–3 alternatives, each with a computed suitability
  /// percentage against this soil reading — see [CropReferenceData]. Empty
  /// only if computed before this field existed (e.g. an old saved report
  /// restored from history).
  final List<CropSuitability> cropSuitabilities;

  /// The single most pressing nutrient/pH/moisture issue in this reading,
  /// or null when every reading is in its optimal band.
  final SoilIssue? primaryIssue;

  /// The 4-step "Recommended Action Plan" shown on the report screen.
  final List<ActionStep> actionPlan;

  /// The "Fertilizer Recommendation" table rows (Nitrogen / Phosphorus /
  /// Potassium / Organic manure), each with a plain-language "why".
  final List<FertilizerRecommendationRow> fertilizerRecommendationRows;
}

