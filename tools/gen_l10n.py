# sanity: every locale has every key
all_keys = set(k for k, _ in KEYS_META)
for loc, d in DATA.items():
    missing = all_keys - set(d.keys())
    extra = set(d.keys()) - all_keys
    if missing:
        raise SystemExit(f"{loc} missing keys: {missing}")
    if extra:
        raise SystemExit(f"{loc} extra keys: {extra}")

import os
out_dir = os.path.join(os.path.dirname(__file__), "..", "lib", "l10n")
os.makedirs(out_dir, exist_ok=True)

# 1) ARB files (source-of-truth / translator-facing artifacts)
locale_order = ["en", "hi", "mr", "kn", "ta", "gu", "te"]
for loc in locale_order:
    arb = {"@@locale": loc}
    for key, desc in KEYS_META:
        arb[key] = DATA[loc][key]
        if loc == "en":
            entry = {"description": desc}
            if "{seconds}" in DATA[loc][key]:
                entry["placeholders"] = {"seconds": {"type": "String"}}
            if "{phone}" in DATA[loc][key]:
                entry["placeholders"] = {"phone": {"type": "String"}}
            if "{name}" in DATA[loc][key]:
                entry["placeholders"] = {"name": {"type": "String"}}
            arb[f"@{key}"] = entry
    with open(f"{out_dir}/app_{loc}.arb", "w", encoding="utf-8") as f:
        json.dump(arb, f, ensure_ascii=False, indent=2)
        f.write("\n")

print("ARB files written for:", locale_order)
print("Total keys per locale:", len(all_keys))

