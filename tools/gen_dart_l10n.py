# -*- coding: utf-8 -*-
"""
Generates:
  krishinetra/lib/l10n/l10n_strings.g.dart  — raw string tables per locale
  krishinetra/lib/l10n/app_localizations.dart — typed accessor class + delegate

Source of truth: l10n_data.json (keys + all 7 locales' strings), itself
produced by gen_l10n.py from the KEYS_META/DATA tables (also used to emit
the .arb files under lib/l10n/ as translator-facing artifacts).

No Flutter SDK is available in this sandbox, so this is a hand-rolled
localization layer (LocalizationsDelegate + a plain class with typed
getters/methods) rather than `flutter gen-l10n` codegen from the .arb
files. The .arb files remain the human-readable/translator source of
truth; this script is what keeps the Dart runtime code mechanically in
sync with them instead of hand-transcribing ~400 strings.
"""
import json
import os

with open(os.path.join(os.path.dirname(__file__), "l10n_data.json"), "r", encoding="utf-8") as f:
    payload = json.load(f)

KEYS = payload["keys"]
DATA = payload["data"]
LOCALES = ["en", "hi", "mr", "kn", "ta", "gu", "te"]

PLACEHOLDER_KEYS = {
    "resendOtpIn": "seconds",
    "codeSentTo": "phone",
    "welcomeBack": "name",
    "schemesStateMismatchWarning": "state",
}

OUT_DIR = os.path.join(os.path.dirname(__file__), "..", "lib", "l10n")


def dart_string_literal(s: str) -> str:
    escaped = s.replace("\\", "\\\\").replace("'", "\\'").replace("\n", "\\n")
    return f"'{escaped}'"


# ---------------------------------------------------------------------------
# 1) l10n_strings.g.dart — plain data, no logic
# ---------------------------------------------------------------------------
lines = []
lines.append("// GENERATED FILE — do not edit by hand.")
lines.append("// Produced by gen_dart_l10n.py from l10n_data.json / the app_*.arb files.")
lines.append("// Regenerate instead of hand-editing if translations change.")
lines.append("")
lines.append("/// Raw localized-string tables, keyed by ISO locale code then by")
lines.append("/// message key. Consumed only by [AppLocalizations] — screens should")
lines.append("/// never read this map directly.")
lines.append("const Map<String, Map<String, String>> kL10nStrings = {")
for loc in LOCALES:
    lines.append(f"  {dart_string_literal(loc)}: {{")
    for key in KEYS:
        lines.append(f"    {dart_string_literal(key)}: {dart_string_literal(DATA[loc][key])},")
    lines.append("  },")
lines.append("};")
lines.append("")

with open(f"{OUT_DIR}/l10n_strings.g.dart", "w", encoding="utf-8") as f:
    f.write("\n".join(lines))

# ---------------------------------------------------------------------------
# 2) app_localizations.dart — typed getters + delegate (structure is fixed
#    hand-authored logic; only the getter list is generated from KEYS so it
#    can't drift out of sync with the string tables above).
# ---------------------------------------------------------------------------
getter_lines = []
for key in KEYS:
    if key in PLACEHOLDER_KEYS:
        continue
    getter_lines.append(f"  String get {key} => _t({dart_string_literal(key)});")

method_lines = []
for key, param in PLACEHOLDER_KEYS.items():
    method_lines.append(
        f"  String {key}(String {param}) =>\n"
        f"      _t({dart_string_literal(key)}).replaceAll('{{{param}}}', {param});"
    )

dart = f"""// GENERATED FILE — getter list is generated by gen_dart_l10n.py from
// l10n_data.json so it can never drift out of sync with kL10nStrings.
// Class structure/delegate logic is hand-authored; regenerate the getter
// block instead of hand-editing it if keys change.
import 'package:flutter/foundation.dart' show SynchronousFuture;
import 'package:flutter/material.dart';

import 'l10n_strings.g.dart';

/// KrishiNetra's app-level localizations. Hand-rolled (no `flutter
/// gen-l10n` codegen — no Flutter SDK is available in the build sandbox
/// this was authored in) but mirrors the shape of a generated
/// AppLocalizations class: one typed getter per simple message, one
/// method per message with placeholders.
///
/// Source of truth for the actual translated text is `lib/l10n/app_*.arb`
/// (translator-facing) / `l10n_data.json` (build-facing) — never edit the
/// strings in this file or in `l10n_strings.g.dart` directly.
class AppLocalizations {{
  AppLocalizations(this.locale);

  final Locale locale;

  static const List<Locale> supportedLocales = <Locale>[
    Locale('en'),
    Locale('hi'),
    Locale('mr'),
    Locale('kn'),
    Locale('ta'),
    Locale('gu'),
    Locale('te'),
  ];

  static const LocalizationsDelegate<AppLocalizations> delegate =
      _AppLocalizationsDelegate();

  static AppLocalizations of(BuildContext context) {{
    final AppLocalizations? instance =
        Localizations.of<AppLocalizations>(context, AppLocalizations);
    assert(
      instance != null,
      'AppLocalizations.of() called with a context that has no '
      'AppLocalizations ancestor. Make sure AppLocalizations.delegate is '
      'registered in MaterialApp.localizationsDelegates.',
    );
    return instance ?? AppLocalizations(const Locale('en'));
  }}

  /// Looks up [key] in the active locale's table, falling back to English
  /// (and finally to the key itself) so a missing translation never
  /// crashes the UI or shows a blank string.
  String _t(String key) {{
    final String? value = kL10nStrings[locale.languageCode]?[key];
    if (value != null) return value;
    return kL10nStrings['en']?[key] ?? key;
  }}

{chr(10).join(getter_lines)}

{chr(10).join(method_lines)}
}}

class _AppLocalizationsDelegate extends LocalizationsDelegate<AppLocalizations> {{
  const _AppLocalizationsDelegate();

  @override
  bool isSupported(Locale locale) => AppLocalizations.supportedLocales
      .any((Locale l) => l.languageCode == locale.languageCode);

  @override
  Future<AppLocalizations> load(Locale locale) {{
    return SynchronousFuture<AppLocalizations>(AppLocalizations(locale));
  }}

  @override
  bool shouldReload(_AppLocalizationsDelegate old) => false;
}}
"""

with open(f"{OUT_DIR}/app_localizations.dart", "w", encoding="utf-8") as f:
    f.write(dart)

print("Wrote l10n_strings.g.dart and app_localizations.dart")
print("Simple getters:", len(getter_lines), "| Placeholder methods:", len(method_lines))
